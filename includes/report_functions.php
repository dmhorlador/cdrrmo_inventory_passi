<?php
// ── Convert logos to base64 data-URIs so they work in the about:blank print window ──
$logo_left_path  = __DIR__ . '/../images/logo.jpg';
$logo_right_path = __DIR__ . '/../images/logo1.png';

$logo_left_b64  = '';
$logo_right_b64 = '';

if (file_exists($logo_left_path)) {
    $logo_left_b64 = 'data:image/jpeg;base64,' . base64_encode(file_get_contents($logo_left_path));
}
if (file_exists($logo_right_path)) {
    $logo_right_b64 = 'data:image/png;base64,' . base64_encode(file_get_contents($logo_right_path));
